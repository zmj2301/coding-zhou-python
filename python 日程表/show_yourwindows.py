class _MessageBox:
    @staticmethod
    def showwarning(title, msg): QMessageBox.warning(None, str(title), str(msg))
    @staticmethod
    def showinfo(title, msg): QMessageBox.information(None, str(title), str(msg))
    @staticmethod
    def showerror(title, msg): QMessageBox.critical(None, str(title), str(msg))
    @staticmethod
    def askquestion(title, msg):
        r = QMessageBox.question(None, str(title), str(msg),
                                 QMessageBox.Yes | QMessageBox.No, QMessageBox.No)
        return 'yes' if r == QMessageBox.Yes else 'no'
    @staticmethod
    def askokcancel(title, msg):
        r = QMessageBox.question(None, str(title), str(msg),
                                 QMessageBox.Ok | QMessageBox.Cancel, QMessageBox.Cancel)
        return r == QMessageBox.Ok
messagebox = _MessageBox()

class _FileDialog:
    @staticmethod
    def askopenfilename(**kw):
        default_dir = kw.get('initialdir') or os.getcwd()
        ft = kw.get('filetypes') or [("All files", "*.*")]
        filter_str = ';;'.join(f"{n} ({p})" for n, p in ft)
        f, _ = QFileDialog.getOpenFileName(None, kw.get('title', '选择文件'),
                                           default_dir, filter_str)
        return f
    @staticmethod
    def asksaveasfilename(**kw):
        default_dir = kw.get('initialdir') or os.getcwd()
        ft = kw.get('filetypes') or [("All files", "*.*")]
        filter_str = ';;'.join(f"{n} ({p})" for n, p in ft)
        f, _ = QFileDialog.getSaveFileName(None, kw.get('title', '保存文件'),
                                           kw.get('defaultextension', ''), filter_str)
        return f
filedialog = _FileDialog()

